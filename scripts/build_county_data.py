"""Build the browser-ready county dataset from the CDC PLACES CSV.

This intentionally mirrors notebooks/county_wise_analysis.ipynb:
- 2025 PLACES county release
- crude prevalence only
- unique counties identified by StateAbbr + LocationID
- complete cases only; no mean imputation
- four-component financial-hardship average
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd


PROJECT_DIR = Path(__file__).resolve().parents[1]
INPUT_PATH = PROJECT_DIR / "data" / "places_county_2025.csv"
OUTPUT_PATH = PROJECT_DIR / "county-data.js"

MEASURES = {
    "depression": "Depression among adults",
    "housing": "Housing insecurity in the past 12 months among adults",
    "utility": "Utility services shut-off threat in the past 12 months among adults",
    "food": "Food insecurity in the past 12 months among adults",
    "stamps": "Received food stamps in the past 12 months among adults",
    "distress_actual": "Frequent mental distress among adults",
}

MODEL = {
    "intercept": 5.270755185105916,
    "depression": 0.36379008682090513,
    "financial_hardship": 0.27627603774643467,
}


def main() -> None:
    if not INPUT_PATH.exists():
        raise FileNotFoundError(f"CDC dataset not found: {INPUT_PATH}")

    raw = pd.read_csv(INPUT_PATH, low_memory=False)
    selected = raw.loc[
        raw["Measure"].isin(MEASURES.values())
        & raw["Data_Value_Type"].eq("Crude prevalence")
        & raw["LocationName"].notna()
        & raw["StateAbbr"].ne("US"),
        [
            "StateAbbr",
            "StateDesc",
            "LocationID",
            "LocationName",
            "Measure",
            "Data_Value",
        ],
    ].copy()

    key = ["StateAbbr", "StateDesc", "LocationID", "LocationName"]
    if selected.duplicated(key + ["Measure"]).any():
        raise ValueError("Duplicate county-measure rows found; refusing to aggregate silently")

    wide = selected.pivot(index=key, columns="Measure", values="Data_Value").reset_index()
    wide.columns.name = None
    wide = wide.rename(columns={full: short for short, full in MEASURES.items()})
    required = list(MEASURES)
    complete = wide.dropna(subset=required).copy()

    components = ["housing", "utility", "food", "stamps"]
    complete["financial_hardship"] = complete[components].mean(axis=1)
    complete["distress_predicted"] = (
        MODEL["intercept"]
        + MODEL["depression"] * complete["depression"]
        + MODEL["financial_hardship"] * complete["financial_hardship"]
    )

    records = []
    for row in complete.sort_values(["StateAbbr", "LocationName"]).itertuples():
        records.append(
            {
                "id": str(int(row.LocationID)).zfill(5),
                "abbr": row.StateAbbr,
                "state": row.StateDesc,
                "name": row.LocationName,
                "depression": round(float(row.depression), 3),
                "financial_hardship": round(float(row.financial_hardship), 3),
                "distress_actual": round(float(row.distress_actual), 3),
                "distress_predicted": round(float(row.distress_predicted), 3),
            }
        )

    if len(records) != 2299:
        raise ValueError(f"Expected 2,299 complete counties, found {len(records):,}")

    payload = json.dumps(records, separators=(",", ":"))
    output = (
        "/* Generated by scripts/build_county_data.py from the same CDC PLACES "
        "2025 county CSV and complete-case rules used by the county notebook. */\n"
        f"const COUNTIES = Object.freeze({payload}.map(Object.freeze));\n"
        "const COUNTIES_BY_ID = Object.freeze(Object.fromEntries(COUNTIES.map(c => [c.id, c])));\n"
    )
    OUTPUT_PATH.write_text(output, encoding="utf-8")
    print(f"Wrote {len(records):,} counties to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
